import json
from pathlib import Path
from typing import Any, Dict


class ExperimentLogger:
    """
    Save research results generated by HLI-01 experiments.
    """

    def __init__(self, experiment_dir: Path):
        self.experiment_dir = Path(experiment_dir)

        if not self.experiment_dir.exists():
            raise FileNotFoundError(
                f"Experiment directory not found: {self.experiment_dir}"
            )

    def save_metrics(self, metrics: Dict[str, Any]) -> Path:
        """
        Save evaluation metrics to metrics.json.
        """

        metrics_path = self.experiment_dir / "metrics.json"

        with open(metrics_path, "w", encoding="utf-8") as file:
            json.dump(metrics, file, indent=4)

        return metrics_path

    def save_training_history(self, history: Dict[str, Any]) -> Path:
        """
        Save training history to training_history.json.
        """

        history_path = self.experiment_dir / "training_history.json"

        with open(history_path, "w", encoding="utf-8") as file:
            json.dump(history, file, indent=4)

        return history_path